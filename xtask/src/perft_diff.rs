//! `cargo xtask perft-diff`: find where Backrank's move generation disagrees with Stockfish.
//!
//! Both engines split perft by first move. If a move's count differs, that move is played
//! and the comparison repeats one ply shallower, until the exact position with a missing or
//! extra move is found.

use crate::paths;
use anyhow::{Context, Result, bail, ensure};
use std::collections::BTreeMap;
use std::io::Write;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

#[derive(clap::Args)]
pub struct Args {
    /// Starting position as a FEN string (default: the standard start position).
    #[arg(long)]
    fen: Option<String>,
    /// Perft depth to compare at.
    #[arg(long)]
    depth: u32,
}

/// A perft split by first move.
#[derive(Debug, PartialEq, Eq)]
struct Divide {
    /// Leaf count for each first move, keyed by its UCI name.
    moves: BTreeMap<String, u64>,
    total: u64,
}

/// How two splits of the same position relate.
#[derive(Debug, PartialEq, Eq)]
enum Comparison {
    Same,
    /// The engines disagree about which moves are legal here: this is the bug.
    DifferentMoves {
        missing: Vec<String>,
        extra: Vec<String>,
    },
    /// Same moves, but this one leads to a different count: look below it.
    Descend {
        mv: String,
        ours: u64,
        theirs: u64,
    },
}

fn compare(ours: &Divide, theirs: &Divide) -> Comparison {
    let missing: Vec<String> = theirs
        .moves
        .keys()
        .filter(|m| !ours.moves.contains_key(*m))
        .cloned()
        .collect();
    let extra: Vec<String> = ours
        .moves
        .keys()
        .filter(|m| !theirs.moves.contains_key(*m))
        .cloned()
        .collect();
    if !missing.is_empty() || !extra.is_empty() {
        return Comparison::DifferentMoves { missing, extra };
    }
    match ours.moves.iter().find(|(m, n)| theirs.moves[*m] != **n) {
        Some((mv, &n)) => Comparison::Descend {
            mv: mv.clone(),
            ours: n,
            theirs: theirs.moves[mv],
        },
        None => Comparison::Same,
    }
}

pub fn run(args: &Args) -> Result<()> {
    ensure!(args.depth >= 1, "--depth must be at least 1");
    let stockfish = paths::stockfish();
    ensure!(
        stockfish.exists(),
        "{} is missing; run `cargo xtask setup` first",
        stockfish.display()
    );
    let backrank = build_backrank()?;
    let start = match &args.fen {
        Some(fen) => format!("fen {fen}"),
        None => "startpos".to_string(),
    };

    let mut moves: Vec<String> = Vec::new();
    let mut depth = args.depth;
    loop {
        let ours = backrank_divide(&backrank, &start, &moves, depth)?;
        let theirs = stockfish_divide(&stockfish, &start, &moves, depth)?;
        let line = describe(&start, &moves);
        match compare(&ours, &theirs) {
            Comparison::Same if moves.is_empty() => {
                println!(
                    "perft {depth}: Backrank and Stockfish agree ({} nodes)",
                    ours.total
                );
                return Ok(());
            }
            Comparison::Same => bail!(
                "the engines agree at {line}, yet gave different counts for its last move one \
                 level up: one engine's perft output is inconsistent"
            ),
            Comparison::Descend { mv, ours, theirs } => {
                println!("{line}, depth {depth}: {mv} gives {ours} (Stockfish {theirs})");
                moves.push(mv);
                depth -= 1;
            }
            Comparison::DifferentMoves { missing, extra } => {
                println!();
                println!("Found it, at {line}:");
                println!("  FEN: {}", stockfish_fen(&stockfish, &start, &moves)?);
                if !missing.is_empty() {
                    println!(
                        "  legal but not generated by Backrank: {}",
                        missing.join(" ")
                    );
                }
                if !extra.is_empty() {
                    println!("  generated by Backrank but illegal: {}", extra.join(" "));
                }
                bail!("move generation differs from Stockfish");
            }
        }
    }
}

fn describe(start: &str, moves: &[String]) -> String {
    if moves.is_empty() {
        start.to_string()
    } else {
        format!("{start} moves {}", moves.join(" "))
    }
}

fn build_backrank() -> Result<PathBuf> {
    let cargo = std::env::var("CARGO").unwrap_or_else(|_| "cargo".to_string());
    let status = Command::new(cargo)
        .args([
            "build",
            "--release",
            "--quiet",
            "--package",
            "backrank",
            "--bin",
            "backrank",
        ])
        .current_dir(paths::root())
        .status()
        .context("failed to run cargo build")?;
    ensure!(status.success(), "building backrank failed");
    Ok(paths::root().join("target/release/backrank"))
}

fn backrank_divide(binary: &Path, start: &str, moves: &[String], depth: u32) -> Result<Divide> {
    let mut command = Command::new(binary);
    command
        .arg("perft")
        .arg(depth.to_string())
        .args(start.split_whitespace());
    if !moves.is_empty() {
        command.arg("moves").args(moves);
    }
    let output = command.output().context("failed to run backrank perft")?;
    ensure!(
        output.status.success(),
        "backrank perft failed: {}",
        String::from_utf8_lossy(&output.stderr).trim()
    );
    parse_divide(&String::from_utf8_lossy(&output.stdout))
}

/// Runs a UCI script through Stockfish and returns everything it printed.
fn stockfish_session(stockfish: &Path, script: &str) -> Result<String> {
    let mut child = Command::new(stockfish)
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::null())
        .spawn()
        .context("failed to start Stockfish")?;
    child
        .stdin
        .take()
        .expect("stdin is piped")
        .write_all(script.as_bytes())?;
    let output = child.wait_with_output()?;
    Ok(String::from_utf8_lossy(&output.stdout).into_owned())
}

fn position_command(start: &str, moves: &[String]) -> String {
    let mut command = format!("position {start}");
    if !moves.is_empty() {
        command.push_str(" moves ");
        command.push_str(&moves.join(" "));
    }
    command
}

fn stockfish_divide(stockfish: &Path, start: &str, moves: &[String], depth: u32) -> Result<Divide> {
    let script = format!(
        "{}\ngo perft {depth}\nquit\n",
        position_command(start, moves)
    );
    parse_divide(&stockfish_session(stockfish, &script)?)
        .context("parsing Stockfish's perft output")
}

fn stockfish_fen(stockfish: &Path, start: &str, moves: &[String]) -> Result<String> {
    let script = format!("{}\nd\nquit\n", position_command(start, moves));
    let output = stockfish_session(stockfish, &script)?;
    output
        .lines()
        .find_map(|line| line.strip_prefix("Fen: "))
        .map(str::to_string)
        .context("Stockfish's `d` output has no Fen line")
}

/// Parses `move: count` lines and the `Nodes searched: N` total, ignoring anything else
/// (such as Stockfish's `info string` lines).
fn parse_divide(text: &str) -> Result<Divide> {
    let mut moves = BTreeMap::new();
    let mut total = None;
    for line in text.lines().map(str::trim) {
        if let Some(n) = line.strip_prefix("Nodes searched: ") {
            total = Some(n.parse().context("bad node total")?);
        } else if let Some((mv, n)) = line.split_once(": ")
            && is_uci_move(mv)
        {
            moves.insert(mv.to_string(), n.parse().context("bad node count")?);
        }
    }
    let total = total.context("no `Nodes searched:` line in perft output")?;
    Ok(Divide { moves, total })
}

fn is_uci_move(text: &str) -> bool {
    let b = text.as_bytes();
    let square = |f: u8, r: u8| (b'a'..=b'h').contains(&f) && (b'1'..=b'8').contains(&r);
    match b {
        [f1, r1, f2, r2] => square(*f1, *r1) && square(*f2, *r2),
        [f1, r1, f2, r2, p] => square(*f1, *r1) && square(*f2, *r2) && b"nbrq".contains(p),
        _ => false,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn divide(pairs: &[(&str, u64)]) -> Divide {
        Divide {
            moves: pairs.iter().map(|&(m, n)| (m.to_string(), n)).collect(),
            total: pairs.iter().map(|&(_, n)| n).sum(),
        }
    }

    #[test]
    fn parses_stockfish_style_output() {
        let text = "info string some banner\na2a3: 380\nb7b8q: 12\n\nNodes searched: 392\n";
        assert_eq!(
            parse_divide(text).unwrap(),
            divide(&[("a2a3", 380), ("b7b8q", 12)])
        );
        assert!(parse_divide("a2a3: 1\n").is_err());
    }

    #[test]
    fn recognises_uci_moves() {
        for m in ["e2e4", "a7a8q", "h2h1n"] {
            assert!(is_uci_move(m), "{m}");
        }
        for m in ["e2e9", "e7e8k", "Nodes searched", "e2", "info string x"] {
            assert!(!is_uci_move(m), "{m}");
        }
    }

    #[test]
    fn compares_splits() {
        let a = divide(&[("e2e4", 20), ("d2d4", 20)]);
        assert_eq!(compare(&a, &a), Comparison::Same);
        let b = divide(&[("e2e4", 20), ("d2d4", 21)]);
        assert_eq!(
            compare(&a, &b),
            Comparison::Descend {
                mv: "d2d4".into(),
                ours: 20,
                theirs: 21
            }
        );
        let c = divide(&[("e2e4", 20), ("g1f3", 20)]);
        assert_eq!(
            compare(&a, &c),
            Comparison::DifferentMoves {
                missing: vec!["g1f3".into()],
                extra: vec!["d2d4".into()]
            }
        );
    }
}
